package org.example;
public class Main {
    static void main() {
        short valorShort = 3;
        int valorInt = valorShort;
        byte valorByte = (byte)valorShort;
        System.out.println("Valor do short: " + valorShort);
        System.out.println("Valor do int: " + valorInt);
        System.out.println("Valor do byte: " + valorByte);
    }
}